public class PRIMITIVE_VARIABLE_2
{
    public static void main(String[] args)
    {
        int age = 19; //declare age in int = integer
        System.out.println("Age : " + age);

        double gpa = 4.00; //declare gpa in double = decimal number
        System.out.println("GPA : " + gpa);

        char grade = 'A'; //declare grade in char = character, needs to use single quote
        System.out.println("Grade : " + grade);

        boolean isStudent = true; //declare isStudent (is a student or not) in boolean which represent as "true" or "false"
        System.out.println("Is a student : " + isStudent);
    }
}
