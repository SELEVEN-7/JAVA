public class PRINT_1 //declare class Main
{
    public static void main(String[] args)
    {
        /*
        This is a
        multi-line
        comment
         */

      System.out.println("TANG"); //println=print+go to next line
      System.out.print("TANG"); //just print and stay at same line
      System.out.print("\nTANG"); //if \n in front of output,go next line first then print
      System.out.print("TANG\n"); //if \n is behind output,print first then go to next line
      System.out.println("TANG"); //Use "sout" shortcut which represent "System.out.println();"
    }
}
