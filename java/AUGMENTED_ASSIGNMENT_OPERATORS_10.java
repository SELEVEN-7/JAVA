public class AUGMENTED_ASSIGNMENT_OPERATORS_10
{
    public static void  main (String[] args)
    {
        int x = 10;
        int y = 2;

        x += y; //x = x + y
        x -= y; //x = x - y
        x *= y; //x = x * y
        x /= y; //x = x / y
        x %= y; //x = x % y

        System.out.println(x);

    }
}
