public class ARITHMETIC_OPERATORS_9
{
    public static void  main (String[] args)
    {
        int x = 10, y = 2, z;
        z = x + y; //addition
        z = x - y; //subtraction
        z = x * y; //multiplication
        z = x / y; //division
        z = x % y; //modulus (get remainder)
        System.out.println(z);
    }
}
